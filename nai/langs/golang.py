"""Go adapter: ``go.mod`` module, ``go test -json`` results, panic stubs.

Layout (mirrors the Python/Swift adapters)::

    go.mod                                generated module file
    internal/<component>/<component>.go    contract stub / implementation
    internal/<component>/<component>_test.go  frozen tests
    internal/entities/entities.go          shared contract entities

The adapter owns ``go.mod``.  ``go build``/``go vet`` decide BUILD_ERROR and
``go test -json`` gives machine-readable results, so nothing here relies on
matching human prose.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

from . import _common
from .base import Command, Outcome, ParseResult, StubFile, StubResult, TestCase, ToolCheck

STUB_MARKER = 'panic("not implemented")'
CRASH_MARKER = "not implemented"

_GO_ERROR = re.compile(r"^(?:#.*|.+?\.go:\d+(?::\d+)?:\s+.+)$", re.M)
_GO_TEST = re.compile(r"^func\s+(Test[A-Za-z0-9_]*)\s*\(", re.M)
_GO_BUILD_LINE = re.compile(r"^\.?.*?\.go:\d+(?::\d+)?:\s+", re.M)
_GO_IMPORT = re.compile(r'^\s*(?:import\s+)?(?:[\w.]+\s+)?"([^"]+)"', re.M)

#: UI toolkits a portable (``any``/``linux``) component must not import.
_UI_MODULES = frozenset({
    "github.com/fyne-io/fyne",
    "fyne.io/fyne",
    "github.com/andlabs/ui",
    "github.com/lxn/walk",
    "github.com/therecipe/qt",
})

#: Go type names for the contract's Python-ish type names.
_GO_TYPES = {
    "str": "string", "string": "string", "text": "string",
    "int": "int", "integer": "int", "float": "float64", "double": "float64",
    "number": "float64", "bool": "bool", "boolean": "bool",
    "date": "time.Time", "any": "any", "object": "map[string]string",
    "dict": "map[string]string", "map": "map[string]string", "list": "[]string",
}


def go_module(project: dict[str, Any]) -> str:
    """The module path: ``settings.go.module`` when set, else the project name."""
    settings = (project or {}).get("settings") or {}
    block = settings.get("go") if isinstance(settings, dict) else None
    declared = str((block or {}).get("module") or "").strip() if isinstance(block, dict) else ""
    if declared:
        return declared.strip("/")
    return _common.kebab(str((project or {}).get("name") or "project"), fallback="project")


def go_package(node: dict[str, Any]) -> str:
    """The Go package name for a component (lower snake case)."""
    return _common.snake(str(node.get("name") or "component"))


def go_type(raw: Any, entities: tuple[str, ...] = ()) -> str:
    """Map a contract type to Go."""
    text = str(raw or "").strip()
    lower = text.lower()
    if not text or lower in ("void", "none", "null", "nil"):
        return ""
    if text.endswith("?"):
        return "*" + go_type(text.rstrip("?"), entities)
    if lower in _GO_TYPES:
        return _GO_TYPES[lower]
    bracket = re.fullmatch(r"(?:list|array|set)\s*[\[<]\s*(.+?)\s*\]", text, re.I)
    if bracket:
        return "[]" + go_type(bracket.group(1), entities)
    bracket = re.fullmatch(r"(.+)\[\]", text)
    if bracket:
        return "[]" + go_type(bracket.group(1), entities)
    if text in entities:
        return text
    return "string"


def render_entities(entities: list[dict[str, Any]]) -> str:
    """Render the shared contract entities as one Go package."""
    lines = [
        "// Code generated by nai contract stubs. DO NOT EDIT.",
        "",
        "package entities",
        "",
    ]
    names = tuple(_common.pascal(str(e.get("name") or "")) for e in entities)
    for entity in entities:
        name = _common.pascal(str(entity.get("name") or "Entity"))
        description = str(entity.get("description") or "").strip()
        if description:
            lines.append(f"// {name} {description}")
        lines.append(f"type {name} struct {{")
        for field in entity.get("fields") or []:
            if not isinstance(field, dict):
                continue
            field_name = _common.pascal(str(field.get("name") or "Value"))
            field_type = go_type(field.get("type"), names)
            if not field.get("required", True):
                field_type = "*" + field_type if field_type and not field_type.startswith("*") else field_type
            lines.append(f"\t{field_name} {field_type or 'any'}")
        lines.append("}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _uses_entities(component: dict[str, Any], names: tuple[str, ...]) -> bool:
    for provide in component.get("provides") or []:
        if not isinstance(provide, dict):
            continue
        _name, params, returns = _common.parse_provide(provide)
        for _param, kind in params:
            if kind in names:
                return True
        if returns in names:
            return True
    return False


class GoAdapter:
    """Adapter for Go modules built with ``go build`` and tested with ``go test``."""

    id = "go"
    display_name = "Go"
    test_framework = "go test"
    extensions: tuple[str, ...] = (".go",)
    stub_marker = STUB_MARKER
    stack_hint = "Go 1.22"
    style_guide = (
        "- Return errors instead of panicking; only contract stubs panic.\n"
        "- Keep components in `internal/<package>` with one exported operation per file.\n"
        "- Name tests `Test_<REQ-ID>_<Behaviour>` so traceability can find them.\n"
        "- Format with `gofmt`; the adapter owns `go.mod` and `internal/entities`."
    )
    toolchain: tuple[ToolCheck, ...] = (
        ToolCheck("go", ("go", "version")),
        ToolCheck("gofmt", ("gofmt", "-h"), required=False),
    )

    # -- layout ------------------------------------------------------------
    def package_name(self, project: dict[str, Any]) -> str:
        return go_module(project)

    def module_import(self, project: dict[str, Any], node: dict[str, Any]) -> str:
        return f"{go_module(project)}/internal/{go_package(node)}"

    def source_rel(self, project: dict[str, Any], node: dict[str, Any]) -> str:
        package = go_package(node)
        return f"internal/{package}/{package}.go"

    def test_rel(self, project: dict[str, Any], node: dict[str, Any]) -> str:
        package = go_package(node)
        return f"internal/{package}/{package}_test.go"

    def entities_rel(self, project: dict[str, Any]) -> str:
        return "internal/entities/entities.go"

    def normalize_test_path(self, raw_path: str, node: dict[str, Any]) -> str:
        package = go_package(node)
        return f"internal/{package}/{package}_test.go"

    def protected_globs(self, project: dict[str, Any]) -> tuple[str, ...]:
        return ("go.mod", "go.sum", "internal/entities/**", "*_test.go")

    def writable_globs(self, project: dict[str, Any], node: dict[str, Any]) -> tuple[str, ...]:
        return (self.source_rel(project, node), f"internal/{go_package(node)}/**")

    def snapshot_ignore(self) -> tuple[str, ...]:
        return (".git", "bin", "vendor")

    def cache_dirs(self) -> tuple[str, ...]:
        return ("bin",)

    # -- environment and workspace -----------------------------------------
    def needs_target_env(self) -> bool:
        return False

    def prepare_workspace(self, project: dict[str, Any], workspace_root: Path) -> tuple[str, ...]:
        """Regenerate ``go.mod`` when the module path drifts."""
        manifest = f"module {go_module(project)}\n\ngo 1.22\n"
        path = Path(workspace_root) / "go.mod"
        if path.is_file() and path.read_text(encoding="utf-8") == manifest:
            return ()
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(manifest, encoding="utf-8")
        return ("go.mod",)

    def environment_block(self, project: dict[str, Any], workspace_root: Path) -> str:
        return (
            "## Target Environment (TENV-4)\n"
            f"- {self.stack_hint} module `{go_module(project)}`; no third-party dependencies.\n"
            "- Components live in `internal/<package>`; tests use the standard `testing` package.\n"
            "- The adapter owns `go.mod`; never edit it or add dependencies."
        )

    # -- stubs -------------------------------------------------------------
    def render_stub(
        self,
        project: dict[str, Any],
        node: dict[str, Any],
        contract: dict[str, Any] | None,
    ) -> StubResult:
        shared = _common.entities(contract)
        files: list[StubFile] = []
        if shared:
            files.append(StubFile(self.entities_rel(project), render_entities(shared)))
        files.append(StubFile(self.source_rel(project, node), self._render_source(project, node, contract, shared)))
        return StubResult(
            files=tuple(files),
            module_import=self.module_import(project, node),
            package_name=self.package_name(project),
        )

    def _render_source(
        self,
        project: dict[str, Any],
        node: dict[str, Any],
        contract: dict[str, Any] | None,
        shared: list[dict[str, Any]],
    ) -> str:
        package = go_package(node)
        lines = [
            f"// Code generated by nai contract stubs for {node.get('name')}. Keep the signatures; implement the bodies.",
            "",
            f"package {package}",
            "",
        ]
        if str(node.get("kind") or "") == "integration":
            lines.append("// Integrate runs the parent contract's scenarios and returns the observed outcome.")
            lines.append("func Integrate() int {")
            lines.append(f"\t{STUB_MARKER}")
            lines.append("}")
            lines.append("")
            return "\n".join(lines)
        names = tuple(_common.pascal(str(e.get("name") or "")) for e in shared)
        component = _common.component_entry(contract, node)
        if shared and _uses_entities(component, names):
            lines.append(f'import "{go_module(project)}/internal/entities"')
            lines.append("")
        provides = [p for p in (component.get("provides") or []) if isinstance(p, dict)]
        if not provides:
            lines.append(f"// {package} has no contract operations yet.")
            lines.append("")
            return "\n".join(lines)
        for provide in provides:
            name, params, returns = _common.parse_provide(provide)
            description = str(provide.get("description") or "").strip() or f"Contract operation {name}."
            lines.append(f"// {_common.pascal(name)} {description}")
            rendered = ", ".join(
                f"{_common.camel(param)} {go_type(kind, names) or 'string'}" for param, kind in params
            )
            suffix = f" {go_type(returns, names)}" if go_type(returns, names) else ""
            lines.append(f"func {_common.pascal(name)}({rendered}){suffix} {{")
            lines.append(f"\t{STUB_MARKER}")
            lines.append("}")
            lines.append("")
        return "\n".join(lines).rstrip() + "\n"

    def validate_stub(
        self,
        workspace_root: Path,
        module_import: str,
        run_cmd: Any,
        *,
        executable: str | None = None,
        run_setup_cmd: Any | None = None,
    ) -> tuple[bool, str]:
        code, output = run_cmd("go build ./...")
        return code == 0, output

    def extract_signatures(self, source: str) -> str:
        """Exported declarations only, never implementations (BLD-1)."""
        found: list[str] = []
        for line in (source or "").splitlines():
            stripped = line.strip()
            if stripped.startswith("func ") or stripped.startswith("type "):
                found.append(stripped.rstrip("{").rstrip())
        return "\n".join(found)

    # -- commands ----------------------------------------------------------
    def setup_commands(self, project: dict[str, Any], workspace_root: Path) -> tuple[Command, ...]:
        """No third-party dependencies: ``go mod tidy`` only when a module exists."""
        return (Command(argv=("go", "mod", "tidy"), network=False),)

    def build_commands(self, project: dict[str, Any], workspace_root: Path) -> tuple[Command, ...]:
        return (
            Command(argv=("go", "build", "./..."), network=False),
            Command(argv=("go", "vet", "./..."), network=False),
        )

    def test_command(
        self,
        project: dict[str, Any],
        node: dict[str, Any],
        *,
        scope: str | None = None,
        paths: tuple[str, ...] = (),
    ) -> Command:
        target = "./..."
        if paths:
            rel = str(paths[0]).replace("\\", "/").strip().strip("/")
            # ``go test`` takes package patterns, not files: a path to a test
            # file means "the package that contains it".
            package = rel.rsplit("/", 1)[0] if rel.endswith(".go") else rel
            target = f"./{package}/..." if package else "./..."
        return Command(argv=("go", "test", "-json", "-count=1", target), network=False)

    def lint_command(
        self,
        project: dict[str, Any],
        workspace_root: Path,
        targets: tuple[str, ...],
    ) -> Command | None:
        """``go vet`` runs as a build step; ``gofmt -l`` is the format gate."""
        if not targets:
            return None
        return Command(argv=("gofmt", "-l", *targets), network=False)

    def env_overrides(self, project: dict[str, Any], workspace_root: Path) -> dict[str, str]:
        return {"GOFLAGS": "-mod=mod", "GO111MODULE": "on", "CGO_ENABLED": "0"}

    # -- results -----------------------------------------------------------
    def parse_result(
        self,
        raw_output: str,
        exit_code: int,
        kind: str,
        *,
        timed_out: bool = False,
    ) -> ParseResult:
        """Classify ``go build``/``go vet``/``go test -json`` output."""
        text = raw_output or ""
        if timed_out:
            return ParseResult(Outcome.TIMEOUT, exit_code=exit_code, raw_output=text, timed_out=True)
        cases = _go_cases(text)
        errors = _go_errors(text)
        marker = CRASH_MARKER in text
        # ``go build``/``go vet`` report no tests; only a test run can be NO_TESTS.
        zero_tests = kind != "build" and not cases
        if exit_code == 0:
            outcome = Outcome.NO_TESTS if zero_tests else Outcome.PASS
        elif kind == "build" or (errors and not cases):
            outcome = Outcome.BUILD_ERROR
        else:
            outcome = Outcome.TEST_FAIL
        return ParseResult(
            outcome=outcome,
            exit_code=exit_code,
            tests=cases,
            failure_messages=errors,
            raw_output=text,
            marker_present=marker,
        )

    def stub_failure_is_valid(
        self,
        result: ParseResult,
        *,
        integration: bool = False,
        expected_module: str | None = None,
    ) -> bool:
        """Valid only when the build passed and the run panicked on the stub."""
        if result.timed_out:
            return False
        if result.outcome in (Outcome.PASS, Outcome.NO_TESTS):
            return False
        if result.outcome is Outcome.BUILD_ERROR:
            # Integration nodes have no contract stub: the expected pre-stub
            # state is the missing integration package, not a panic.
            return bool(
                integration
                and _common.integration_build_failure(result.raw_output, expected_module or "")
            )
        return result.marker_present

    def extract_test_functions(self, test_sources: dict[str, str]) -> tuple[list[str], list[str]]:
        """``func TestR1_<behaviour>(t *testing.T)`` names."""
        names: list[str] = []
        errors: list[str] = []
        for path, source in sorted(test_sources.items()):
            text = str(source or "")
            if not text.strip():
                errors.append(f"{path}: empty test file")
                continue
            found = [match.group(1) for match in _GO_TEST.finditer(text)]
            if not found:
                errors.append(f"{path}: no Test* function found")
            names.extend(found)
        return names, errors

    def check_syntax(self, code: str, filename: str) -> str | None:
        """Structural pre-check (balanced brackets, closed literals)."""
        return _common.structural_error(code, filename)

    # -- platform lint -----------------------------------------------------
    def platform_lint(
        self,
        project: dict[str, Any],
        node: dict[str, Any],
        workspace_root: Path,
        *,
        platform: str = "any",
    ) -> tuple[str, ...]:
        """A portable component may not import a UI toolkit."""
        if str(platform).lower() not in ("any", "linux"):
            return ()
        root = Path(workspace_root)
        base = root / "internal" / go_package(node)
        if not base.is_dir():
            return ()
        findings: list[str] = []
        for path in sorted(base.rglob("*.go")):
            try:
                text = path.read_text(encoding="utf-8", errors="replace")
            except OSError:  # pragma: no cover - unreadable file is reported by verify
                continue
            for match in _GO_IMPORT.finditer(text):
                module = match.group(1)
                if any(module == ui or module.startswith(f"{ui}/") for ui in _UI_MODULES):
                    findings.append(
                        f"{path.relative_to(root).as_posix()}: imports {module}; "
                        f"a platform {platform} component must not import UI frameworks"
                    )
        return tuple(findings)

    # -- remote execution --------------------------------------------------
    def remote_recipe(
        self, project: dict[str, Any], node: dict[str, Any], job_kind: str, *, platform: str = "any"
    ) -> str:
        if job_kind in ("verify", "author_tests", "integrate", "lint"):
            return "go-test"
        return "go-build"

    def remote_params(
        self,
        project: dict[str, Any],
        node: dict[str, Any],
        job_kind: str,
        *,
        targets: tuple[str, ...] = (),
        platform: str = "any",
    ) -> dict[str, Any]:
        if job_kind in ("verify", "author_tests", "integrate"):
            return {"filter": f"./internal/{go_package(node)}/..."}
        return {}


def _go_cases(text: str) -> tuple[TestCase, ...]:
    """Collapse ``go test -json`` events into one ``TestCase`` per test."""
    seen: dict[str, str] = {}
    messages: dict[str, str] = {}
    order: list[str] = []
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped.startswith("{"):
            continue
        try:
            event = json.loads(stripped)
        except ValueError:
            continue
        if not isinstance(event, dict):
            continue
        name = str(event.get("Test") or "")
        action = str(event.get("Action") or "")
        if not name:
            continue
        if action == "output":
            output = str(event.get("Output") or "").strip()
            if output and not output.startswith(("=== RUN", "--- PASS", "--- FAIL", "PASS", "FAIL", "ok ")):
                messages.setdefault(name, output)
            continue
        if action not in ("pass", "fail", "skip"):
            continue
        if name not in seen:
            order.append(name)
        seen[name] = action
        if action == "fail":
            messages.setdefault(name, _go_failure_detail(text, name))
    return tuple(
        TestCase(
            name=name,
            outcome={"pass": "passed", "fail": "failed", "skip": "skipped"}.get(seen[name], "error"),
            message=messages.get(name, "")[:2000],
        )
        for name in order
    )


def _go_failure_detail(text: str, name: str) -> str:
    """The ``--- FAIL: <name>`` block's message lines, when present."""
    collecting = False
    collected: list[str] = []
    for line in text.splitlines():
        if f"--- FAIL: {name}" in line:
            collecting = True
            continue
        if collecting:
            if line.startswith(("--- ", "=== ", "FAIL", "ok ")):
                break
            collected.append(line.strip())
    return " ".join(part for part in collected if part)[:2000]


def _go_errors(text: str) -> tuple[str, ...]:
    """Compiler/vet diagnostics plus panic lines (``file.go:12:3: msg``)."""
    found: list[str] = []
    for line in text.splitlines():
        stripped = line.strip()
        if _GO_BUILD_LINE.match(stripped) or stripped.startswith("panic:"):
            found.append(stripped)
    return tuple(dict.fromkeys(found))
