"""Rust adapter: Cargo workspace, ``cargo build --message-format=json``, libtest.

Layout (one crate per component, mirroring the Python/Swift/Go adapters)::

    Cargo.toml                              generated workspace manifest
    crates/<crate>/Cargo.toml               generated crate manifest
    crates/<crate>/src/lib.rs               contract stub / implementation
    crates/<crate>/tests/<crate>_test.rs    frozen integration tests
    crates/entities/src/lib.rs              shared contract entities
    target/                                 build cache, never committed

The adapter owns every ``Cargo.toml``.  ``cargo build --message-format=json``
gives structured compiler diagnostics for BUILD_ERROR and libtest's stable text
output gives per-test results, so nothing depends on matching human prose.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

from . import _common
from .base import Command, Outcome, ParseResult, StubFile, StubResult, TestCase, ToolCheck

STUB_MARKER = "unimplemented!()"
CRASH_MARKER = "not implemented"

_CARGO_ERROR = re.compile(r"^error(\[[A-Za-z0-9]+\])?:\s*(?P<msg>.+)$", re.M)
#: ``--message-format=short`` puts the location first: ``path:line:col: error[E0308]: …``.
_CARGO_SHORT_ERROR = re.compile(r"^[^\s].*?:\d+(?::\d+)?:\s+error(?:\[[A-Za-z0-9]+\])?:\s+.+$", re.M)
_TEST_LINE = re.compile(r"^test\s+(?P<name>.+?)\s+\.\.\.\s+(?P<result>ok|FAILED|ignored)\s*$", re.M)
_ZERO_TESTS = re.compile(r"^running 0 tests$", re.M)
_USE = re.compile(r"^\s*use\s+([A-Za-z_][A-Za-z0-9_]*)::", re.M)
_RUST_TEST_FN = re.compile(r"#\[test\]\s*(?:#\[[^\]]*\]\s*)*fn\s+([A-Za-z_][A-Za-z0-9_]*)", re.M)

#: Rust's view of the contract's Python-ish type names (owned, for returns).
_RUST_TYPES = {
    "str": "String", "string": "String", "text": "String",
    "int": "i64", "integer": "i64", "float": "f64", "double": "f64",
    "number": "f64", "bool": "bool", "boolean": "bool",
    "date": "String", "uuid": "String", "any": "String",
    "object": "HashMap<String, String>", "dict": "HashMap<String, String>",
    "map": "HashMap<String, String>", "list": "Vec<String>",
}

#: UI crates a portable component must not depend on.
_UI_MODULES = frozenset({"iced", "egui", "gtk", "gtk4", "slint", "druid", "relm4"})


def rust_workspace_name(project: dict[str, Any]) -> str:
    """The workspace prefix used for the entities crate."""
    settings = (project or {}).get("settings") or {}
    block = settings.get("rust") if isinstance(settings, dict) else None
    declared = str((block or {}).get("workspace") or "").strip() if isinstance(block, dict) else ""
    raw = declared or str((project or {}).get("name") or "project")
    return _common.snake(raw, fallback="project")


def rust_crate(node: dict[str, Any]) -> str:
    """The crate name for a component (lower snake case)."""
    return _common.snake(str(node.get("name") or "component"))


def rust_entities_crate(project: dict[str, Any]) -> str:
    """The shared-entities crate name; it matches its directory ``crates/entities``."""
    return "entities"


def rust_type(raw: Any, entities: tuple[str, ...] = ()) -> str:
    """Map a contract type to an owned Rust type."""
    text = str(raw or "").strip()
    lower = text.lower()
    if not text or lower in ("void", "none", "null", "unit"):
        return "()"
    if text.endswith("?"):
        return f"Option<{rust_type(text.rstrip('?'), entities)}>"
    if lower.startswith("optional[") and text.endswith("]"):
        return f"Option<{rust_type(text[len('optional['):-1], entities)}>"
    if lower in _RUST_TYPES:
        return _RUST_TYPES[lower]
    bracket = re.fullmatch(r"(?:list|array|set)\s*[\[<]\s*(.+?)\s*[\]]", text, re.I)
    if bracket:
        return f"Vec<{rust_type(bracket.group(1), entities)}>"
    if text in entities or re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", text):
        return text
    return "String"


def rust_param_type(raw: Any, entities: tuple[str, ...] = ()) -> str:
    """Borrowed parameter type: ``&str``, ``&[String]``, ``&Entity``."""
    owned = rust_type(raw, entities)
    if owned in ("()", "String"):
        return "&str"
    if owned.startswith("Vec<"):
        return f"&{owned}"
    if owned.startswith("Option<"):
        return owned
    if owned in entities:
        return f"&{owned}"
    return owned


def render_entities(entities: list[dict[str, Any]]) -> str:
    """Render the shared contract entities as one crate's ``lib.rs``."""
    lines = [
        "// Generated by nai from the frozen contract. Do not edit: the adapter regenerates this file.",
        "",
    ]
    names = tuple(_common.pascal(str(e.get("name") or "")) for e in entities)
    needs_map = any(
        "HashMap" in rust_type(f.get("type"), names)
        for entity in entities
        for f in (entity.get("fields") or [])
        if isinstance(f, dict)
    )
    if needs_map:
        lines.append("use std::collections::HashMap;")
        lines.append("")
    for entity in entities:
        if not isinstance(entity, dict):
            continue
        name = _common.pascal(str(entity.get("name") or "Entity"))
        description = str(entity.get("description") or "").strip()
        if description:
            lines.append(f"/// {description}")
        lines.append("#[derive(Debug, Clone, PartialEq)]")
        lines.append(f"pub struct {name} {{")
        for field in entity.get("fields") or []:
            if not isinstance(field, dict):
                continue
            field_name = _common.snake(str(field.get("name") or "value"))
            field_type = rust_type(field.get("type"), names)
            if not field.get("required", True):
                field_type = f"Option<{field_type}>" if not field_type.startswith("Option<") else field_type
            lines.append(f"    pub {field_name}: {field_type},")
        lines.append("}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _uses_entities(component: dict[str, Any], names: tuple[str, ...]) -> bool:
    for provide in component.get("provides") or []:
        if not isinstance(provide, dict):
            continue
        _name, params, returns = _common.parse_provide(provide)
        for _param, kind in params:
            if kind in names:
                return True
        if returns in names:
            return True
    return False


def _crate_dirs(workspace_root: Path) -> list[str]:
    """Crate names whose ``crates/<name>/src/lib.rs`` exists on disk."""
    base = Path(workspace_root) / "crates"
    if not base.is_dir():
        return []
    # ``crates/<name>/src/lib.rs`` -> ``path.parent`` is ``src``, so the crate
    # name lives one level further up.
    return sorted(
        path.parent.parent.name
        for path in base.glob("*/src/lib.rs")
        if path.parent.parent.name and path.parent.parent.name != "entities"
    )


def render_workspace_manifest(project: dict[str, Any], workspace_root: Path) -> str:
    """The workspace manifest: only crates that exist on disk are members."""
    crates = _crate_dirs(workspace_root)
    members = ['"crates/entities"'] + [f'"crates/{crate}"' for crate in crates]
    lines = [
        "# Generated by nai. The adapter owns this file; do not edit it.",
        "[workspace]",
        'resolver = "2"',
        "members = [",
    ]
    lines.extend(f"    {member}," for member in members)
    lines.append("]")
    lines.append("")
    return "\n".join(lines)


def render_crate_manifest(
    project: dict[str, Any], crate: str, dependencies: tuple[str, ...] = ()
) -> str:
    """One crate manifest; path dependencies are relative to ``crates/``."""
    lines = [
        "# Generated by nai. The adapter owns this file; do not edit it.",
        "[package]",
        f'name = "{crate}"',
        'version = "0.1.0"',
        'edition = "2021"',
        "",
    ]
    if dependencies:
        lines.append("[dependencies]")
        for dep in dependencies:
            lines.append(f'{dep} = {{ path = "../{dep}" }}')
        lines.append("")
    return "\n".join(lines)


def _component_manifest_deps(
    project: dict[str, Any], crate: str, libs: list[str], *, has_entities: bool
) -> tuple[str, ...]:
    """Path dependencies for one crate: entities plus the contract's edges."""
    deps: list[str] = []
    entities = rust_entities_crate(project)
    if has_entities and crate != entities:
        deps.append(entities)
    component = next(
        (c for c in _common.components(project) if _common.snake(str(c.get("name") or "")) == crate),
        {},
    )
    for dep in component.get("depends_on") or []:
        dep_crate = _common.snake(str(dep))
        if dep_crate in libs and dep_crate != crate and dep_crate not in deps:
            deps.append(dep_crate)
    if crate.endswith("_integration"):
        for other in libs:
            if other != crate and not other.endswith("_integration") and other not in deps:
                deps.append(other)
    return tuple(deps)


def _write_if_changed(path: Path, content: str) -> bool:
    """Write *content* only when it differs; return whether the file changed."""
    if path.is_file() and path.read_text(encoding="utf-8") == content:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return True


class RustAdapter:
    """Adapter for Rust workspaces built with ``cargo`` and tested with libtest."""

    id = "rust"
    display_name = "Rust"
    test_framework = "libtest (cargo test)"
    extensions = (".rs",)
    stub_marker = STUB_MARKER
    stack_hint = "Rust 1.75 (edition 2021)"
    style_guide = (
        "- Return `Result<T, E>` for fallible operations; only contract stubs panic.\n"
        "- Use owned types in signatures and borrow (`&str`, `&[T]`) for parameters.\n"
        "- Name tests `test_<req_id>_<behaviour>` so traceability can find them.\n"
        "- Run `cargo fmt`; the adapter owns every `Cargo.toml`."
    )
    toolchain = (
        ToolCheck("cargo", ("cargo", "--version")),
        ToolCheck("rustc", ("rustc", "--version")),
        ToolCheck("rustfmt", ("rustfmt", "--version"), required=False),
    )

    # -- layout ------------------------------------------------------------
    def package_name(self, project: dict[str, Any]) -> str:
        return rust_workspace_name(project)

    def module_import(self, project: dict[str, Any], node: dict[str, Any]) -> str:
        return rust_crate(node)

    def source_rel(self, project: dict[str, Any], node: dict[str, Any]) -> str:
        return f"crates/{rust_crate(node)}/src/lib.rs"

    def test_rel(self, project: dict[str, Any], node: dict[str, Any]) -> str:
        return f"crates/{rust_crate(node)}/tests/{rust_crate(node)}_test.rs"

    def entities_rel(self, project: dict[str, Any]) -> str:
        return "crates/entities/src/lib.rs"

    def normalize_test_path(self, raw_path: str, node: dict[str, Any]) -> str:
        crate = rust_crate(node)
        return f"crates/{crate}/tests/{crate}_test.rs"

    def protected_globs(self, project: dict[str, Any]) -> tuple[str, ...]:
        return ("Cargo.toml", "crates/*/Cargo.toml", "crates/*/tests/**", "crates/entities/**")

    def writable_globs(self, project: dict[str, Any], node: dict[str, Any]) -> tuple[str, ...]:
        return (self.source_rel(project, node), f"crates/{rust_crate(node)}/src/**")

    def snapshot_ignore(self) -> tuple[str, ...]:
        return (".git", "target")

    def cache_dirs(self) -> tuple[str, ...]:
        return ("target",)

    # -- environment and workspace -----------------------------------------
    def needs_target_env(self) -> bool:
        return False

    def prepare_workspace(self, project: dict[str, Any], workspace_root: Path) -> tuple[str, ...]:
        """Regenerate the workspace and every crate manifest when they drift."""
        root = Path(workspace_root)
        written: list[str] = []
        libs = _crate_dirs(root)
        has_entities = (root / "crates" / "entities" / "src" / "lib.rs").is_file()
        for crate in libs:
            deps = _component_manifest_deps(project, crate, libs, has_entities=has_entities)
            rel = f"crates/{crate}/Cargo.toml"
            if _write_if_changed(root / rel, render_crate_manifest(project, crate, deps)):
                written.append(rel)
        if has_entities:
            rel = "crates/entities/Cargo.toml"
            if _write_if_changed(root / rel, render_crate_manifest(project, "entities")):
                written.append(rel)
        rel = "Cargo.toml"
        if _write_if_changed(root / rel, render_workspace_manifest(project, root)):
            written.append(rel)
        return tuple(written)

    def environment_block(self, project: dict[str, Any], workspace_root: Path) -> str:
        return (
            "## Target Environment (TENV-4)\n"
            f"- {self.stack_hint}; one crate per component under `crates/`.\n"
            "- The adapter owns every `Cargo.toml`; never edit them or add dependencies.\n"
            "- Tests are integration tests under `crates/<crate>/tests/` using the built-in libtest."
        )

    # -- stubs -------------------------------------------------------------
    def render_stub(
        self,
        project: dict[str, Any],
        node: dict[str, Any],
        contract: dict[str, Any] | None,
    ) -> StubResult:
        shared = _common.entities(contract)
        files: list[StubFile] = []
        if shared:
            files.append(StubFile(self.entities_rel(project), render_entities(shared)))
        files.append(StubFile(self.source_rel(project, node), self._render_source(project, node, contract, shared)))
        return StubResult(
            files=tuple(files),
            module_import=self.module_import(project, node),
            package_name=self.package_name(project),
        )

    def _render_source(
        self,
        project: dict[str, Any],
        node: dict[str, Any],
        contract: dict[str, Any] | None,
        shared: list[dict[str, Any]],
    ) -> str:
        crate = rust_crate(node)
        lines = [
            f"// Generated by nai contract stubs for {node.get('name')}. Keep the signatures; implement the bodies.",
            "",
        ]
        if str(node.get("kind") or "") == "integration":
            lines.append("/// Run the parent contract's scenarios and return the observed outcome.")
            lines.append("pub fn integrate() -> i64 {")
            lines.append(f"    {STUB_MARKER}")
            lines.append("}")
            lines.append("")
            return "\n".join(lines)
        names = tuple(_common.pascal(str(e.get("name") or "")) for e in shared)
        component = _common.component_entry(contract, node)
        if shared and _uses_entities(component, names):
            lines.append(f"use {rust_entities_crate(project)}::{{" + ", ".join(names) + "};")
            lines.append("")
        provides = [p for p in (component.get("provides") or []) if isinstance(p, dict)]
        if not provides:
            lines.append(f"// {crate} has no contract operations yet.")
            lines.append("")
            return "\n".join(lines)
        for provide in provides:
            name, params, returns = _common.parse_provide(provide)
            description = str(provide.get("description") or "").strip() or f"Contract operation {name}."
            lines.append(f"/// {description}")
            rendered = ", ".join(
                f"{_common.snake(param)}: {rust_param_type(kind, names)}" for param, kind in params
            )
            suffix = f" -> {rust_type(returns, names)}" if rust_type(returns, names) != "()" else ""
            lines.append(f"pub fn {_common.snake(name)}({rendered}){suffix} {{")
            lines.append(f"    {STUB_MARKER}")
            lines.append("}")
            lines.append("")
        return "\n".join(lines).rstrip() + "\n"

    def validate_stub(
        self,
        workspace_root: Path,
        module_import: str,
        run_cmd: Any,
        *,
        executable: str | None = None,
        run_setup_cmd: Any | None = None,
    ) -> tuple[bool, str]:
        code, output = run_cmd("cargo build --workspace --message-format=short")
        return code == 0, output

    def extract_signatures(self, source: str) -> str:
        """Public declarations only, never implementations (BLD-1)."""
        found: list[str] = []
        for line in (source or "").splitlines():
            stripped = line.strip()
            if stripped.startswith("pub fn ") or stripped.startswith("pub struct "):
                found.append(stripped.rstrip("{").rstrip())
        return "\n".join(found)

    # -- commands ----------------------------------------------------------
    def setup_commands(self, project: dict[str, Any], workspace_root: Path) -> tuple[Command, ...]:
        """No dependencies to fetch; ``cargo metadata`` validates the workspace."""
        return (Command(argv=("cargo", "metadata", "--no-deps", "--format-version=1"), network=False),)

    def build_commands(self, project: dict[str, Any], workspace_root: Path) -> tuple[Command, ...]:
        return (
            Command(argv=("cargo", "build", "--workspace", "--message-format=json"), network=False),
        )

    def test_command(
        self,
        project: dict[str, Any],
        node: dict[str, Any],
        *,
        scope: str | None = None,
        paths: tuple[str, ...] = (),
    ) -> Command:
        crate = rust_crate(node)
        # Target the crate's integration test binary only: ``cargo test`` also
        # runs doc-tests, whose "running 0 tests" line would look like a
        # zero-test run to the verification gate.
        return Command(
            argv=(
                "cargo",
                "test",
                "-p",
                crate,
                "--test",
                f"{crate}_test",
                "--",
                "--test-threads=1",
            ),
            network=False,
        )

    def lint_command(
        self,
        project: dict[str, Any],
        workspace_root: Path,
        targets: tuple[str, ...],
    ) -> Command | None:
        """``cargo fmt --check`` when rustfmt is installed; cargo owns the build."""
        return Command(argv=("cargo", "fmt", "--all", "--check"), network=False)

    def env_overrides(self, project: dict[str, Any], workspace_root: Path) -> dict[str, str]:
        return {"CARGO_TERM_COLOR": "never", "RUST_BACKTRACE": "1"}

    # -- results -----------------------------------------------------------
    def parse_result(
        self,
        raw_output: str,
        exit_code: int,
        kind: str,
        *,
        timed_out: bool = False,
    ) -> ParseResult:
        """Classify ``cargo build --message-format=json`` and libtest output."""
        text = raw_output or ""
        if timed_out:
            return ParseResult(Outcome.TIMEOUT, exit_code=exit_code, raw_output=text, timed_out=True)
        cases = _rust_cases(text)
        errors = _cargo_errors(text)
        marker = CRASH_MARKER in text
        zero_tests = kind != "build" and not cases and bool(_ZERO_TESTS.search(text))
        if exit_code == 0:
            outcome = Outcome.NO_TESTS if zero_tests else Outcome.PASS
        elif kind == "build" or (errors and not cases):
            outcome = Outcome.BUILD_ERROR
        else:
            outcome = Outcome.TEST_FAIL
        return ParseResult(
            outcome=outcome,
            exit_code=exit_code,
            tests=cases,
            failure_messages=errors,
            raw_output=text,
            marker_present=marker,
        )

    def stub_failure_is_valid(
        self,
        result: ParseResult,
        *,
        integration: bool = False,
        expected_module: str | None = None,
    ) -> bool:
        """Valid only when the build succeeded and the run hit the stub panic."""
        if result.timed_out:
            return False
        if result.outcome in (Outcome.PASS, Outcome.NO_TESTS):
            return False
        if result.outcome is Outcome.BUILD_ERROR:
            # Integration nodes have no contract stub: the expected pre-stub
            # state is the missing integration crate, not a panic.
            return bool(
                integration
                and _common.integration_build_failure(result.raw_output, expected_module or "")
            )
        return result.marker_present

    def extract_test_functions(self, test_sources: dict[str, str]) -> tuple[list[str], list[str]]:
        """``#[test] fn test_<id>_<behaviour>()`` names."""
        names: list[str] = []
        errors: list[str] = []
        for path, source in sorted(test_sources.items()):
            text = str(source or "")
            if not text.strip():
                errors.append(f"{path}: empty test file")
                continue
            found = [match.group(1) for match in _RUST_TEST_FN.finditer(text)]
            if not found:
                errors.append(f"{path}: no #[test] fn found")
            names.extend(found)
        return names, errors

    def check_syntax(self, code: str, filename: str) -> str | None:
        """Structural pre-check; lifetimes (``'a``) are not char literals."""
        return _common.structural_error(code, filename, char_literals=False)

    # -- platform lint -----------------------------------------------------
    def platform_lint(
        self,
        project: dict[str, Any],
        node: dict[str, Any],
        workspace_root: Path,
        *,
        platform: str = "any",
    ) -> tuple[str, ...]:
        """A portable component may not depend on a UI crate."""
        if str(platform).lower() not in ("any", "linux"):
            return ()
        root = Path(workspace_root)
        base = root / "crates" / rust_crate(node) / "src"
        if not base.is_dir():
            return ()
        findings: list[str] = []
        for path in sorted(base.rglob("*.rs")):
            try:
                text = path.read_text(encoding="utf-8", errors="replace")
            except OSError:  # pragma: no cover - unreadable file is reported by verify
                continue
            for match in _USE.finditer(text):
                if match.group(1) in _UI_MODULES:
                    findings.append(
                        f"{path.relative_to(root).as_posix()}: uses {match.group(1)}; "
                        f"a platform {platform} component must not depend on UI crates"
                    )
        return tuple(findings)

    # -- remote execution --------------------------------------------------
    def remote_recipe(
        self, project: dict[str, Any], node: dict[str, Any], job_kind: str, *, platform: str = "any"
    ) -> str:
        if job_kind in ("verify", "author_tests", "integrate", "lint"):
            return "cargo-test"
        return "cargo-build"

    def remote_params(
        self,
        project: dict[str, Any],
        node: dict[str, Any],
        job_kind: str,
        *,
        targets: tuple[str, ...] = (),
        platform: str = "any",
    ) -> dict[str, Any]:
        if job_kind in ("verify", "author_tests", "integrate"):
            return {"filter": rust_crate(node)}
        return {}


def _rust_cases(text: str) -> tuple[TestCase, ...]:
    """Parse libtest's stable ``test <name> ... ok`` lines."""
    found: list[TestCase] = []
    for match in _TEST_LINE.finditer(text):
        name = match.group("name").strip()
        result = match.group("result")
        outcome = "passed" if result == "ok" else ("skipped" if result == "ignored" else "failed")
        message = _rust_failure_detail(text, name) if outcome == "failed" else ""
        found.append(TestCase(name=name, outcome=outcome, message=message[:2000]))
    return tuple(found)


def _rust_failure_detail(text: str, name: str) -> str:
    """Lines between ``---- <name> stdout ----`` and the next section."""
    collecting = False
    collected: list[str] = []
    for line in text.splitlines():
        stripped = line.strip()
        if stripped == f"---- {name} stdout ----":
            collecting = True
            continue
        if collecting:
            if stripped.startswith("---- ") or stripped == "failures:":
                break
            collected.append(stripped)
    return " ".join(part for part in collected if part)[:2000]


def _cargo_errors(text: str) -> tuple[str, ...]:
    """Structured compiler diagnostics from ``--message-format=json`` plus stderr."""
    found: list[str] = []
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("{"):
            try:
                event = json.loads(stripped)
            except ValueError:
                continue
            if not isinstance(event, dict) or event.get("reason") != "compiler-message":
                continue
            message = event.get("message") or {}
            if not isinstance(message, dict) or message.get("level") != "error":
                continue
            rendered = str(message.get("rendered") or message.get("message") or "").strip()
            if rendered:
                found.append(rendered)
            continue
        if _CARGO_ERROR.match(stripped):
            found.append(stripped)
            continue
        if _CARGO_SHORT_ERROR.match(stripped):
            found.append(stripped)
    return tuple(dict.fromkeys(found))
