"""TypeScript (Node >= 20, vitest) language adapter.

The adapter owns ``package.json`` and ``tsconfig.json``: both are regenerated
deterministically from the project settings, so the model never edits build
configuration.  Layout::

    package.json                        generated, never hand-edited
    tsconfig.json                       generated
    src/<component>/index.ts            contract stub / implementation
    src/entities.ts                     shared contract entities
    tests/<component>.test.ts           vitest specs
    node_modules/                       installed, never committed

Stubs throw ``new Error("not implemented")``: the build succeeds and the test
run fails with that message, which is exactly the pre-implementation failure the
pipeline proves before implementation.  Results come from vitest's JSON
reporter, and ``tsc --noEmit`` decides BUILD_ERROR.
"""

from __future__ import annotations

import json
import re
from pathlib import Path, PurePosixPath
from typing import Any

from . import _common
from .base import Command, Outcome, ParseResult, StubFile, StubResult, TestCase, ToolCheck

STUB_MARKER = 'throw new Error("not implemented")'
CRASH_MARKER = "not implemented"

_TS_ERROR = re.compile(
    r"^(?P<path>.+?)\((?P<line>\d+),(?P<col>\d+)\):\s*error\s+TS\d+:\s*(?P<msg>.+)$", re.M
)
_TS_ERROR_BARE = re.compile(r"^error\s+TS\d+:\s*(?P<msg>.+)$", re.M)
_TEST_NAME = re.compile(r"\b(?:it|test)\s*\(\s*(['\"`])(?P<name>[^'\"`]+)\1")
_IMPORT = re.compile(r"""^\s*(?:import|export)\b[^;\n]*?from\s*['"](?P<module>[^'"]+)['"]""", re.M)
_UI_MODULES = ("react-native", "expo", "react-dom")

#: TypeScript's view of the contract's Python-ish type names.
_TS_TYPES = {
    "str": "string", "string": "string", "text": "string",
    "int": "number", "integer": "number", "number": "number",
    "float": "number", "double": "number",
    "bool": "boolean", "boolean": "boolean",
    "date": "Date", "uuid": "string",
    "any": "unknown", "object": "Record<string, string>",
    "dict": "Record<string, string>", "map": "Record<string, string>",
    "list": "string[]",
}


def ts_package_name(project: dict[str, Any]) -> str:
    settings = (project or {}).get("settings") or {}
    raw = settings.get("package_name") or (project or {}).get("name") or "app"
    name = _common.kebab(str(raw))
    if name[0].isdigit():
        name = f"app-{name}"
    return name


def ts_type(raw: Any, entities: tuple[str, ...] = ()) -> str:
    """Map a contract type to TypeScript (entities keep their declared name)."""
    text = str(raw or "").strip()
    lower = text.lower()
    if not text or lower in {"none", "null", "void", "unit"}:
        return "void"
    if lower in _TS_TYPES:
        return _TS_TYPES[lower]
    if text.endswith("?"):
        return _as_optional(ts_type(text.rstrip("?"), entities))
    if lower.startswith("optional[") and text.endswith("]"):
        return _as_optional(ts_type(text[len("optional["):-1], entities))
    bracket = re.fullmatch(r"(?:list|array|set)\s*[\[<]\s*(.+?)\s*[\]]", text, re.I)
    if bracket:
        return f"{ts_type(bracket.group(1), entities)}[]"
    if text in entities or re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", text):
        return text
    return "string"


def _as_optional(rendered: str) -> str:
    return rendered if "undefined" in rendered else f"{rendered} | undefined"


def render_entities(entities: list[dict[str, Any]]) -> str:
    """Render the shared contract entities as one TypeScript module."""
    lines = [
        "// Generated by nai from the frozen contract. Do not edit: the adapter regenerates this file.",
        "",
    ]
    for entity in entities:
        if not isinstance(entity, dict):
            continue
        name = _common.pascal(str(entity.get("name") or "Entity"))
        fields = [f for f in (entity.get("fields") or []) if isinstance(f, dict)]
        description = str(entity.get("description") or "").strip()
        if description:
            lines.append(f"/** {description} */")
        lines.append(f"export interface {name} {{")
        for field in fields:
            field_name = _common.camel(str(field.get("name") or "value"))
            field_type = ts_type(field.get("type"), ())
            optional = "?" if not field.get("required", True) else ""
            lines.append(f"  {field_name}{optional}: {field_type};")
        lines.append("}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_tsconfig() -> str:
    """A deterministic, strict ``tsconfig.json`` for the generated layout."""
    config = {
        "compilerOptions": {
            "target": "ES2022",
            "module": "ES2022",
            "moduleResolution": "Bundler",
            "strict": True,
            "noEmit": True,
            "declaration": False,
            "esModuleInterop": True,
            "forceConsistentCasingInFileNames": True,
            "skipLibCheck": True,
        },
        "include": ["src/**/*.ts", "tests/**/*.ts"],
    }
    return json.dumps(config, indent=2, sort_keys=True) + "\n"


def render_package_json(project: dict[str, Any]) -> str:
    """A deterministic ``package.json`` pinning the TypeScript toolchain."""
    payload = {
        "name": ts_package_name(project),
        "version": "0.0.0",
        "private": True,
        "type": "module",
        "scripts": {
            "build": "tsc --noEmit",
            "test": "vitest run --reporter=json",
        },
        "devDependencies": {
            "typescript": "^5.6.0",
            "vitest": "^2.1.0",
        },
    }
    return json.dumps(payload, indent=2, sort_keys=True) + "\n"


def _extract_json(text: str) -> dict[str, Any] | None:
    """Pull the first JSON object out of vitest's stdout."""
    cleaned = re.sub(r"\x1b\[[0-9;]*m", "", text or "")
    start = cleaned.find("{")
    while start != -1:
        try:
            payload, _end = json.JSONDecoder().raw_decode(cleaned[start:])
        except ValueError:
            start = cleaned.find("{", start + 1)
            continue
        if isinstance(payload, dict):
            return payload
        start = cleaned.find("{", start + 1)
    return None


def _cases(payload: dict[str, Any] | None) -> tuple[TestCase, ...]:
    found: list[TestCase] = []
    for file in (payload or {}).get("testResults") or []:
        if not isinstance(file, dict):
            continue
        for assertion in file.get("assertionResults") or []:
            if not isinstance(assertion, dict):
                continue
            name = str(assertion.get("fullName") or assertion.get("title") or "test")
            status = str(assertion.get("status") or "failed")
            outcome = {
                "passed": "passed", "failed": "failed", "pending": "skipped",
                "skipped": "skipped", "todo": "skipped",
            }.get(status, "error")
            message = " ".join(str(m) for m in (assertion.get("failureMessages") or [])[:1])
            found.append(TestCase(name=name, outcome=outcome, message=message[:2000]))
    return tuple(found)


class TypeScriptAdapter:
    """Adapter for TypeScript projects built with ``tsc`` and tested with vitest."""

    id = "typescript"
    display_name = "TypeScript"
    test_framework = "vitest"
    extensions: tuple[str, ...] = (".ts", ".tsx", ".mts", ".cts")
    stub_marker = STUB_MARKER
    stack_hint = "Node 20 / TypeScript 5 / vitest"
    style_guide = (
        "- Keep library code free of UI frameworks: a `platform = \"any\"` or `linux` component\n"
        "  may import only Node built-ins and its own modules (never react, react-dom,\n"
        "  react-native or expo).\n"
        "- Prefer `const`, explicit return types on exported functions and no `any`.\n"
        "- Name vitest specs `it(\"R1_<behaviour>\", ...)` so traceability can find the requirement id.\n"
        "- Do not edit `package.json`, `tsconfig.json` or `src/entities.ts`; the adapter owns them."
    )
    toolchain: tuple[ToolCheck, ...] = (
        ToolCheck("node", ("node", "--version")),
        ToolCheck("npm", ("npm", "--version")),
        ToolCheck("npx", ("npx", "--version"), required=False),
    )

    # -- layout ------------------------------------------------------------
    def package_name(self, project: dict[str, Any]) -> str:
        return ts_package_name(project)

    def module_import(self, project: dict[str, Any], node: dict[str, Any]) -> str:
        return _common.kebab(str(node.get("name") or "component"))

    def source_rel(self, project: dict[str, Any], node: dict[str, Any]) -> str:
        return f"src/{self.module_import(project, node)}/index.ts"

    def test_rel(self, project: dict[str, Any], node: dict[str, Any]) -> str:
        return f"tests/{self.module_import(project, node)}.test.ts"

    def entities_rel(self, project: dict[str, Any]) -> str:
        return "src/entities.ts"

    def normalize_test_path(self, raw_path: str, node: dict[str, Any]) -> str:
        target = _common.kebab(str(node.get("name") or "component"))
        stem = PurePosixPath(str(raw_path or "").replace("\\", "/")).name or f"{target}.test.ts"
        stem = re.sub(r"\.(test|spec)?\.?tsx?$", "", stem) or target
        stem = re.sub(r"[^A-Za-z0-9_-]", "-", stem).strip("-") or target
        return f"tests/{stem}.test.ts"

    def protected_globs(self, project: dict[str, Any]) -> tuple[str, ...]:
        return (
            "tests/**",
            "package.json",
            "package-lock.json",
            "tsconfig.json",
            "src/entities.ts",
            "external/**",
        )

    def writable_globs(self, project: dict[str, Any], node: dict[str, Any]) -> tuple[str, ...]:
        return (self.source_rel(project, node), f"src/{self.module_import(project, node)}/**")

    def snapshot_ignore(self) -> tuple[str, ...]:
        return ("node_modules", "dist", "coverage", "*.tsbuildinfo", ".vite")

    def cache_dirs(self) -> tuple[str, ...]:
        return ("node_modules", "dist", "coverage", ".vite")

    # -- environment and workspace -----------------------------------------
    def needs_target_env(self) -> bool:
        return False

    def prepare_workspace(self, project: dict[str, Any], workspace_root: Path) -> tuple[str, ...]:
        """Regenerate the adapter-owned manifests when they drift."""
        root = Path(workspace_root)
        written: list[str] = []
        for rel, content in (
            ("package.json", render_package_json(project)),
            ("tsconfig.json", render_tsconfig()),
        ):
            path = root / rel
            if path.is_file() and path.read_text(encoding="utf-8") == content:
                continue
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            written.append(rel)
        return tuple(written)

    def environment_block(self, project: dict[str, Any], workspace_root: Path) -> str:
        return (
            "## Target Environment (TENV-4)\n"
            f"- Language: {self.stack_hint}; ESM modules (`\"type\": \"module\"`).\n"
            "- Tests: vitest. Import the module under test with a relative path, e.g.\n"
            "  `import { add } from \"../src/adder/index.js\";`.\n"
            "- The adapter owns `package.json`, `tsconfig.json` and `src/entities.ts`; do not edit them.\n"
            "- Do not add dependencies: the toolchain is pinned to TypeScript and vitest."
        )

    # -- stubs -------------------------------------------------------------
    def render_stub(
        self,
        project: dict[str, Any],
        node: dict[str, Any],
        contract: dict[str, Any] | None,
    ) -> StubResult:
        """Render the node's stub plus the shared entities module."""
        shared = _common.entities(contract)
        files: list[StubFile] = []
        if shared:
            files.append(StubFile(self.entities_rel(project), render_entities(shared)))
        files.append(StubFile(self.source_rel(project, node), self._render_source(project, node, contract, shared)))
        return StubResult(
            files=tuple(files),
            module_import=self.module_import(project, node),
            package_name=self.package_name(project),
        )

    def _render_source(
        self,
        project: dict[str, Any],
        node: dict[str, Any],
        contract: dict[str, Any] | None,
        shared: list[dict[str, Any]],
    ) -> str:
        target = self.module_import(project, node)
        lines = [
            f"// Generated by nai contract stubs for {node.get('name')}. Keep the signatures; implement the bodies.",
            "",
        ]
        if shared:
            lines.append('import type { ' + ", ".join(
                _common.pascal(str(e.get("name") or "Entity")) for e in shared
            ) + ' } from "../entities.js";')
            lines.append("")
        if str(node.get("kind") or "") == "integration":
            lines.append("/**")
            lines.append(" * Integration wiring: run the parent contract's scenarios and return the")
            lines.append(" * observed result (0 when a scenario has no numeric outcome).")
            lines.append(" */")
            lines.append("export function integrate(): number {")
            lines.append(f"  {STUB_MARKER};")
            lines.append("}")
            lines.append("")
            return "\n".join(lines)
        entity_names = tuple(_common.pascal(str(e.get("name") or "")) for e in shared)
        component = _common.component_entry(contract, node)
        provides = [p for p in (component.get("provides") or []) if isinstance(p, dict)]
        if not provides:
            lines.append(f"// {target} has no contract operations yet.")
            lines.append("export {};")
            lines.append("")
            return "\n".join(lines)
        for provide in provides:
            name, params, returns = _common.parse_provide(provide)
            description = str(provide.get("description") or "").strip() or f"Contract operation {name}."
            lines.append(f"/** {description} */")
            rendered = ", ".join(
                f"{_common.camel(param)}: {ts_type(kind, entity_names)}" for param, kind in params
            )
            suffix = "" if ts_type(returns, entity_names) == "void" else f": {ts_type(returns, entity_names)}"
            lines.append(f"export function {_common.camel(name)}({rendered}){suffix} {{")
            lines.append(f"  {STUB_MARKER};")
            lines.append("}")
            lines.append("")
        return "\n".join(lines).rstrip() + "\n"

    def validate_stub(
        self,
        workspace_root: Path,
        module_import: str,
        run_cmd: Any,
        *,
        executable: str | None = None,
        run_setup_cmd: Any | None = None,
    ) -> tuple[bool, str]:
        """Install the pinned toolchain (setup phase), then type-check the stubs."""
        root = Path(workspace_root)
        if not (root / "node_modules").is_dir():
            install = "npm ci --no-audit --no-fund" if (root / "package-lock.json").is_file() else (
                "npm install --no-audit --no-fund"
            )
            # npm reaches the registry, and only the setup phase allows network.
            run_install = run_setup_cmd or run_cmd
            code, output = run_install(install)
            if code != 0:
                return False, output
        code, output = run_cmd("npx --no-install tsc --noEmit")
        return code == 0, output

    # -- commands ----------------------------------------------------------
    def setup_commands(self, project: dict[str, Any], workspace_root: Path) -> tuple[Command, ...]:
        """``npm ci`` when a lockfile exists (the one-time install writes it)."""
        root = Path(workspace_root)
        if (root / "package-lock.json").is_file():
            return (Command(argv=("npm", "ci", "--no-audit", "--no-fund")),)
        return (Command(argv=("npm", "install", "--no-audit", "--no-fund")),)

    def build_commands(self, project: dict[str, Any], workspace_root: Path) -> tuple[Command, ...]:
        return (Command(argv=("npx", "--no-install", "tsc", "--noEmit"), network=False),)

    def test_command(
        self,
        project: dict[str, Any],
        node: dict[str, Any],
        *,
        scope: str | None = None,
        paths: tuple[str, ...] = (),
    ) -> Command:
        target = paths[0] if paths else self.test_rel(project, node)
        return Command(
            argv=("npx", "--no-install", "vitest", "run", "--reporter=json", "--no-color", target),
            network=False,
        )

    def lint_command(
        self,
        project: dict[str, Any],
        workspace_root: Path,
        targets: tuple[str, ...],
    ) -> Command | None:
        """``tsc --noEmit`` already runs as the build step; no separate linter."""
        return None

    def env_overrides(self, project: dict[str, Any], workspace_root: Path) -> dict[str, str]:
        return {"CI": "1", "NO_COLOR": "1"}

    # -- results -----------------------------------------------------------
    def parse_result(
        self,
        raw_output: str,
        exit_code: int,
        kind: str,
        *,
        timed_out: bool = False,
    ) -> ParseResult:
        """Classify ``tsc``/vitest output."""
        text = raw_output or ""
        if timed_out:
            return ParseResult(Outcome.TIMEOUT, exit_code=exit_code, raw_output=text, timed_out=True)
        payload = _extract_json(text)
        cases = _cases(payload)
        errors = tuple(
            dict.fromkeys(
                match.group(0).strip()
                for pattern in (_TS_ERROR, _TS_ERROR_BARE)
                for match in pattern.finditer(text)
            )
        )
        marker = CRASH_MARKER in text
        # ``tsc --noEmit`` reports no tests; only a test run can be NO_TESTS.
        total = int(payload.get("numTotalTests") or 0) if payload else 0
        zero_tests = kind != "build" and (
            total == 0
            or (not payload and "No test files found" in text)
            or (not payload and kind == "test")
        )
        if exit_code == 0:
            outcome = Outcome.NO_TESTS if zero_tests else Outcome.PASS
        elif kind == "build" or (errors and not cases):
            outcome = Outcome.BUILD_ERROR
        else:
            outcome = Outcome.TEST_FAIL
        return ParseResult(
            outcome=outcome,
            exit_code=exit_code,
            tests=cases,
            failure_messages=errors,
            raw_output=text,
            marker_present=marker,
        )

    def stub_failure_is_valid(
        self,
        result: ParseResult,
        *,
        integration: bool = False,
        expected_module: str | None = None,
    ) -> bool:
        """A stub is valid when it fails with the marker, not a build error."""
        if result.outcome in (Outcome.PASS, Outcome.NO_TESTS):
            return False
        if result.outcome is Outcome.BUILD_ERROR:
            # Integration nodes have no contract stub: the expected pre-stub
            # state is the missing integration module, not a marker throw.
            return bool(
                integration
                and _common.integration_build_failure(result.raw_output, expected_module or "")
            )
        return result.marker_present

    def extract_test_functions(self, test_sources: dict[str, str]) -> tuple[list[str], list[str]]:
        """``it("R1_…")``/``test("R1_…")`` spec names."""
        names: list[str] = []
        errors: list[str] = []
        for path, source in sorted(test_sources.items()):
            text = str(source or "")
            if not text.strip():
                errors.append(f"{path}: empty test file")
                continue
            found = [match.group("name") for match in _TEST_NAME.finditer(text)]
            if not found:
                errors.append(f"{path}: no it()/test() case found")
            names.extend(found)
        return names, errors

    def check_syntax(self, code: str, filename: str) -> str | None:
        """Structural pre-check (balanced brackets, closed literals)."""
        return _common.structural_error(code, filename)

    # -- platform lint -----------------------------------------------------
    def platform_lint(
        self,
        project: dict[str, Any],
        node: dict[str, Any],
        workspace_root: Path,
        *,
        platform: str = "any",
    ) -> tuple[str, ...]:
        """A portable component may not import a UI framework."""
        if str(platform).lower() not in ("any", "linux"):
            return ()
        root = Path(workspace_root)
        base = root / "src" / self.module_import(project, node)
        if not base.is_dir():
            return ()
        findings: list[str] = []
        for path in sorted(base.rglob("*.ts*")):
            try:
                text = path.read_text(encoding="utf-8", errors="replace")
            except OSError:  # pragma: no cover - unreadable file is reported by verify
                continue
            for match in _IMPORT.finditer(text):
                module = match.group("module")
                if module in _UI_MODULES or module.startswith("@react-native"):
                    findings.append(
                        f"{path.relative_to(root).as_posix()}: imports {module}; "
                        f"a platform {platform} component must not import UI frameworks"
                    )
        return tuple(findings)

    # -- remote execution --------------------------------------------------
    def remote_recipe(
        self, project: dict[str, Any], node: dict[str, Any], job_kind: str, *, platform: str = "any"
    ) -> str:
        if job_kind in ("verify", "author_tests", "integrate", "lint"):
            return "npm-test"
        return "npm-build"

    def remote_params(
        self,
        project: dict[str, Any],
        node: dict[str, Any],
        job_kind: str,
        *,
        targets: tuple[str, ...] = (),
        platform: str = "any",
    ) -> dict[str, Any]:
        if job_kind in ("verify", "author_tests", "integrate"):
            return {"filter": self.test_rel(project, node)}
        return {}

    def extract_signatures(self, source: str) -> str:
        """Exported declarations only, never implementations (BLD-1)."""
        found: list[str] = []
        for line in (source or "").splitlines():
            stripped = line.strip()
            if stripped.startswith("//") or not stripped:
                continue
            if re.match(r"^export\s+(?:async\s+)?(?:function|interface|type|class|const|enum)\b", stripped):
                found.append(stripped.rstrip("{").rstrip())
        return "\n".join(found)
