@pytest.mark.parametrize(
    "sample, exit_code, kind, outcome",
    [
        ("go_test_pass.txt", 0, "test", Outcome.PASS),
        ("go_test_fail.txt", 1, "test", Outcome.TEST_FAIL),
        ("go_test_stub_crash.txt", 1, "test", Outcome.TEST_FAIL),
        ("go_build_error.txt", 1, "build", Outcome.BUILD_ERROR),
        ("go_vet_error.txt", 1, "build", Outcome.BUILD_ERROR),
        ("zero_tests.txt", 0, "test", Outcome.NO_TESTS),
    ],
)
def test_parse_result_matches_captured_samples(
    adapter: GoAdapter, sample: str, exit_code: int, kind: str, outcome: Outcome
) -> None:
    """captured-sample: Go 1.22 ``go test -json`` / ``go build`` / ``go vet``."""
    result = adapter.parse_result(_sample(sample), exit_code, kind)
    assert result.outcome is outcome
    assert result.raw_output


def test_passing_tests_are_listed(adapter: GoAdapter) -> None:
    result = adapter.parse_result(_sample("go_test_pass.txt"), 0, "test")
    assert [(case.name, case.outcome) for case in result.tests] == [
        ("TestR1NormalizeText", "passed")
    ]


def test_failing_tests_keep_the_assertion_message(adapter: GoAdapter) -> None:
    result = adapter.parse_result(_sample("go_test_fail.txt"), 1, "test")
    assert [case.outcome for case in result.tests] == ["failed"]
    assert "got 3, want 2" in result.tests[0].message


def test_stub_panic_is_a_valid_pre_implementation_failure(adapter: GoAdapter) -> None:
    result = adapter.parse_result(_sample("go_test_stub_crash.txt"), 1, "test")
    assert result.marker_present is True
    assert adapter.stub_failure_is_valid(result) is True


def test_build_errors_carry_the_go_diagnostics(adapter: GoAdapter) -> None:
    result = adapter.parse_result(_sample("go_build_error.txt"), 1, "build")
    assert any("undefined: strings" in message for message in result.failure_messages)
    assert adapter.stub_failure_is_valid(result) is False


def test_zero_tests_is_not_a_pass(adapter: GoAdapter) -> None:
    result = adapter.parse_result(_sample("zero_tests.txt"), 0, "test")
    assert result.outcome is Outcome.NO_TESTS
    assert adapter.stub_failure_is_valid(result) is False


def test_an_integration_build_failure_names_the_missing_package(adapter: GoAdapter) -> None:
    output = (
        "internal/root_integration/root_integration.go:6:2: no required module provides "
        'package tiny-library/internal/root_integration; to add it: go get "tiny-library/internal/root_integration"'
    )
    result = adapter.parse_result(output, 1, "build")
    assert result.outcome is Outcome.BUILD_ERROR
    assert adapter.stub_failure_is_valid(
        result, integration=True, expected_module="root_integration"
    )
    assert not adapter.stub_failure_is_valid(result, integration=True, expected_module="other")


def test_timeout_short_circuits(adapter: GoAdapter) -> None:
    result = adapter.parse_result("anything", 124, "test", timed_out=True)
    assert result.outcome is Outcome.TIMEOUT and result.timed_out is True


def test_extract_test_functions_and_traceability(adapter: GoAdapter) -> None:
    source = (
        "package text_normalizer\n"
        "\n"
        'import "testing"\n'
        "\n"
        "func Test_R1_NormalizeText(t *testing.T) {}\n"
        "func Test_R2_Trims(t *testing.T) {}\n"
        "func helper() {}\n"
    )
    functions, errors = adapter.extract_test_functions(
        {"internal/text_normalizer/text_normalizer_test.go": source}
    )
    assert functions == ["Test_R1_NormalizeText", "Test_R2_Trims"]
    assert errors == []

    from nai.build.traceability import check_traceability

    trace = check_traceability(
        [{"id": "R1", "text": "normalize"}, {"id": "R3", "text": "missing"}],
        {"internal/text_normalizer/text_normalizer_test.go": source},
        extractor=adapter.extract_test_functions,
    )
    assert trace.missing == ["R3"]
    assert trace.covered["R1"] == ["Test_R1_NormalizeText"]



