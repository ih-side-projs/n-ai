def test_commands_use_go_tooling(adapter: GoAdapter, tmp_path: Path) -> None:
    project, node = _project(), _node("text-normalizer")
    assert adapter.setup_commands(project, tmp_path)[0].argv == ("go", "mod", "tidy")
    assert [cmd.argv for cmd in adapter.build_commands(project, tmp_path)] == [
        ("go", "build", "./..."),
        ("go", "vet", "./..."),
    ]
    assert adapter.test_command(project, node).argv == (
        "go", "test", "-json", "-count=1", "./...",
    )
    assert adapter.test_command(project, node, paths=("internal/text_normalizer",)).argv == (
        "go", "test", "-json", "-count=1", "./internal/text_normalizer/...",
    )
    # author_tests passes the test *file*: go test only accepts package patterns.
    assert adapter.test_command(
        project, node, paths=("internal/text_normalizer/text_normalizer_test.go",)
    ).argv == (
        "go", "test", "-json", "-count=1", "./internal/text_normalizer/...",
    )
    assert adapter.lint_command(project, tmp_path, ()) is None
    assert adapter.lint_command(project, tmp_path, ("internal/x/x.go",)).argv == (
        "gofmt", "-l", "internal/x/x.go",
    )
    assert adapter.needs_target_env() is False
    assert adapter.env_overrides(project, tmp_path) == {
        "GOFLAGS": "-mod=mod",
        "GO111MODULE": "on",
        "CGO_ENABLED": "0",
    }


