@pytest.mark.parametrize(
    "sample, exit_code, kind, outcome",
    [
        ("test_pass.txt", 0, "test", Outcome.PASS),
        ("test_fail.txt", 101, "test", Outcome.TEST_FAIL),
        ("stub_panic.txt", 101, "test", Outcome.TEST_FAIL),
        ("build_error.txt", 101, "build", Outcome.BUILD_ERROR),
        ("zero_tests.txt", 0, "test", Outcome.NO_TESTS),
    ],
)
def test_parse_result_matches_captured_samples(
    adapter: RustAdapter, sample: str, exit_code: int, kind: str, outcome: Outcome
) -> None:
    """captured-sample: cargo 1.90 / libtest output."""
    result = adapter.parse_result(_sample(sample), exit_code, kind)
    assert result.outcome is outcome
    assert result.raw_output


def test_passing_tests_are_listed(adapter: RustAdapter) -> None:
    result = adapter.parse_result(_sample("test_pass.txt"), 0, "test")
    assert [(case.name, case.outcome) for case in result.tests] == [
        ("r1_normalize_text", "passed")
    ]


def test_failing_tests_keep_the_assertion_message(adapter: RustAdapter) -> None:
    result = adapter.parse_result(_sample("test_fail.txt"), 101, "test")
    assert [case.outcome for case in result.tests] == ["failed"]
    assert "assertion" in result.tests[0].message


def test_stub_panic_is_a_valid_pre_implementation_failure(adapter: RustAdapter) -> None:
    result = adapter.parse_result(_sample("stub_panic.txt"), 101, "test")
    assert result.marker_present is True
    assert adapter.stub_failure_is_valid(result) is True


def test_build_errors_carry_the_cargo_diagnostics(adapter: RustAdapter) -> None:
    result = adapter.parse_result(_sample("build_error.txt"), 101, "build")
    assert any("error[E0308]" in message for message in result.failure_messages)
    assert any("could not compile" in message for message in result.failure_messages)
    assert adapter.stub_failure_is_valid(result) is False


def test_zero_tests_is_not_a_pass(adapter: RustAdapter) -> None:
    result = adapter.parse_result(_sample("zero_tests.txt"), 0, "test")
    assert result.outcome is Outcome.NO_TESTS
    assert adapter.stub_failure_is_valid(result) is False


def test_an_integration_build_failure_names_the_missing_crate(adapter: RustAdapter) -> None:
    output = "error: package ID specification `root_integration` did not match any packages"
    result = adapter.parse_result(output, 101, "build")
    assert result.outcome is Outcome.BUILD_ERROR
    assert adapter.stub_failure_is_valid(
        result, integration=True, expected_module="root_integration"
    )
    assert not adapter.stub_failure_is_valid(result, integration=True, expected_module="other")


def test_timeout_short_circuits(adapter: RustAdapter) -> None:
    result = adapter.parse_result("anything", 124, "test", timed_out=True)
    assert result.outcome is Outcome.TIMEOUT and result.timed_out is True


def test_extract_test_functions_and_traceability(adapter: RustAdapter) -> None:
    source = (
        "#[test]\n"
        "fn r1_normalize_text() {}\n"
        "#[test]\n"
        "fn r2_trims() {}\n"
        "fn helper() {}\n"
    )
    functions, errors = adapter.extract_test_functions(
        {"crates/text_normalizer/tests/text_normalizer_test.rs": source}
    )
    assert functions == ["r1_normalize_text", "r2_trims"]
    assert errors == []

    from nai.build.traceability import check_traceability

    trace = check_traceability(
        [{"id": "R1", "text": "normalize"}, {"id": "R3", "text": "missing"}],
        {"crates/text_normalizer/tests/text_normalizer_test.rs": source},
        extractor=adapter.extract_test_functions,
    )
    assert trace.missing == ["R3"]
    assert trace.covered["R1"] == ["r1_normalize_text"]




