def test_manifests_declare_existing_crates_only(tmp_path: Path) -> None:
    project = _project()
    for crate in ("entities", "text_normalizer"):
        (tmp_path / "crates" / crate / "src").mkdir(parents=True)
        (tmp_path / "crates" / crate / "src" / "lib.rs").write_text("// stub\n", encoding="utf-8")
    manifest = render_workspace_manifest(project, tmp_path)
    assert "[workspace]" in manifest
    assert '"crates/entities"' in manifest
    assert '"crates/text_normalizer"' in manifest
    # The word-counter crate does not exist on disk yet, so it is not declared.
    assert "word_counter" not in manifest
    assert manifest == render_workspace_manifest(project, tmp_path)  # deterministic

    crate = render_crate_manifest(project, "text_normalizer", ("entities",))
    assert 'name = "text_normalizer"' in crate
    assert 'edition = "2021"' in crate
    assert 'entities = { path = "../entities" }' in crate


def test_prepare_workspace_writes_every_manifest_once(
    tmp_path: Path, adapter: RustAdapter
) -> None:
    project = _project()
    for crate in ("entities", "text_normalizer"):
        (tmp_path / "crates" / crate / "src").mkdir(parents=True)
        (tmp_path / "crates" / crate / "src" / "lib.rs").write_text("// stub\n", encoding="utf-8")
    written = adapter.prepare_workspace(project, tmp_path)
    assert set(written) == {
        "crates/text_normalizer/Cargo.toml",
        "crates/entities/Cargo.toml",
        "Cargo.toml",
    }
    assert 'entities = { path = "../entities" }' in (
        tmp_path / "crates/text_normalizer/Cargo.toml"
    ).read_text(encoding="utf-8")
    assert adapter.prepare_workspace(project, tmp_path) == ()


